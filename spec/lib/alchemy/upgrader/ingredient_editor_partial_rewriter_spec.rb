# frozen_string_literal: true

require "rails_helper"
require "alchemy/upgrader"

RSpec.describe Alchemy::Upgrader::IngredientEditorPartialRewriter do
  subject { described_class.new.rewrite(source, "custom_editor") }

  let(:template) { subject[0] }
  let(:manual) { subject[1] }

  context "with a partial generated by the ingredient generator" do
    let(:source) do
      <<~ERB
        <%= content_tag :div,
          class: custom_editor.css_classes,
          data: custom_editor.data_attributes do %>
          <%= element_form.fields_for(:ingredients, custom_editor.ingredient) do |f| %>
            <%= ingredient_label(custom_editor) %>
            <%= f.text_field :value %>
          <% end %>
        <% end %>
      ERB
    end

    it "rewrites it into a component template" do
      expect(template).to eq(<<~ERB)
        <%= content_tag :div,
          class: css_classes,
          data: data_attributes, id: dom_id(ingredient) do %>
          <%= fields_for("element[ingredients_attributes][\#{form_field_counter}]", ingredient) do |f| %><%= ingredient_id_field %>
            <%= ingredient_label %>
            <%= f.text_field :value %>
          <% end %>
        <% end %>
      ERB
      expect(manual).to be(false)
    end
  end

  context "with methods of the ingredient" do
    let(:source) { "<%= custom_editor.settings[:foo] %> <%= custom_editor.value %> <%= custom_editor.dom_id %>" }

    it "calls them on the ingredient" do
      expect(template).to eq("<%= ingredient.settings[:foo] %> <%= ingredient.value %> <%= ingredient.dom_id %>")
    end
  end

  context "with methods of the editor" do
    let(:source) { "<%= custom_editor.form_field_name(:link) %> <%= custom_editor.presence_validation? %>" }

    it "calls them on the component" do
      expect(template).to eq("<%= form_field_name(:link) %> <%= presence_validation? %>")
    end
  end

  context "with removed helpers" do
    let(:source) do
      <<~ERB
        <%= ingredient_label(custom_editor, :link) %>
        <%= render_ingredient_role(custom_editor) %>
        <%= render_hint_for(custom_editor, size: "1x") %>
        <%= render "alchemy/ingredients/shared/anchor", ingredient_editor: custom_editor %>
      ERB
    end

    it "replaces them with the component methods" do
      expect(template).to eq(<<~ERB)
        <%= ingredient_label(:link) %>
        <%= ingredient_role %>
        <%= render_hint_for(ingredient, size: "1x") %>
        <%= render "alchemy/ingredients/shared/anchor", ingredient: ingredient %>
      ERB
      expect(manual).to be(false)
    end
  end

  context "with other locals named alike" do
    let(:source) { "<%= other_custom_editor.value %> <%= custom_editor_foo %>" }

    it "leaves them untouched" do
      expect(template).to eq(source)
    end
  end

  context "with element_form used otherwise" do
    let(:source) { "<%= element_form.object.name %>" }

    it "needs to be migrated by hand" do
      expect(manual).to be(true)
    end
  end

  context "with html options passed to ingredient_label" do
    let(:source) { "<%= ingredient_label(custom_editor, :value, class: 'foo') %>" }

    it "needs to be migrated by hand" do
      expect(manual).to be(true)
    end
  end
end
